#!/usr/bin/env node
'use strict';

/**
 * export-directory-manifest.js — generate the tool list we DECLARE from the tools we SHIP.
 *
 * Why this exists: on 2026-07-29 the Anthropic MCP Directory review found our listing
 * declared 82 tools while the live server exposed 42 — six declared tools no longer existed
 * and five live tools were undeclared. Nothing could have caught it, because the declared
 * list lived only in a web form. This is the same defect class that produced every other
 * failure that week: a DECLARED surface drifting from the ACTUAL surface with no test
 * comparing them (package `files` vs runtime requires, MCP schema vs handler forwarding,
 * a shipped Dockerfile no CI job built).
 *
 * The manifest is generated by booting the real MCP server and asking it — never hand-edited.
 * tests/directory-manifest-parity.test.js fails when the committed file and the live server
 * disagree, so a tool added or removed forces the listing to be updated in the same PR.
 *
 *   node scripts/export-directory-manifest.js            # write config/directory-manifest.json
 *   node scripts/export-directory-manifest.js --check    # exit 1 if committed file is stale
 */

const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { spawn } = require('node:child_process');

const OUT_PATH = path.join(__dirname, '..', 'config', 'directory-manifest.json');
const CLI_PATH = path.join(__dirname, '..', 'bin', 'cli.js');

function liveTools({ timeoutMs = 30000 } = {}) {
  return new Promise((resolve, reject) => {
    // Sandboxed HOME: enumerating the surface must never touch real feedback state.
    const sandbox = fs.mkdtempSync(path.join(os.tmpdir(), 'tg-manifest-'));
    const child = spawn(process.execPath, [CLI_PATH, 'serve'], {
      cwd: path.join(__dirname, '..'),
      env: { PATH: process.env.PATH, HOME: sandbox, THUMBGATE_HOME: path.join(sandbox, '.thumbgate') },
      stdio: ['pipe', 'pipe', 'pipe'],
    });
    let buffer = '';
    let stderr = '';
    const done = (fn, arg) => {
      clearTimeout(timer);
      try { child.kill(); } catch { /* already gone */ }
      fs.rmSync(sandbox, { recursive: true, force: true });
      fn(arg);
    };
    const timer = setTimeout(
      () => done(reject, new Error(`server did not answer tools/list in ${timeoutMs}ms; stderr: ${stderr.slice(0, 300)}`)),
      timeoutMs,
    );
    child.stderr.on('data', (chunk) => { stderr += chunk; });
    child.on('error', (err) => done(reject, err));
    child.stdout.on('data', (chunk) => {
      buffer += chunk;
      for (const line of buffer.split('\n')) {
        if (!line.trim().startsWith('{')) continue;
        let msg;
        try { msg = JSON.parse(line); } catch { continue; }
        if (msg.id === 1 && msg.result && Array.isArray(msg.result.tools)) {
          done(resolve, msg.result.tools);
          return;
        }
      }
    });
    const send = (obj) => child.stdin.write(`${JSON.stringify(obj)}\n`);
    send({ jsonrpc: '2.0', id: 0, method: 'initialize', params: { protocolVersion: '2024-11-05', capabilities: {}, clientInfo: { name: 'directory-manifest', version: '1' } } });
    send({ jsonrpc: '2.0', method: 'notifications/initialized' });
    send({ jsonrpc: '2.0', id: 1, method: 'tools/list' });
  });
}

function buildManifest(tools) {
  const names = tools.map((tool) => tool.name).sort();
  // Disclosure is generated too, and keyed to the tools that actually carry conversation
  // data — the directory review flagged that our listing claimed otherwise while
  // capture_feedback accepted raw chatHistory/conversationWindow.
  const conversationTools = tools
    // Match FIELD NAMES with word boundaries, never a substring scan of the whole schema:
    // /turns/ matched the word "returns" inside a description and produced a false positive
    // (require_evidence_for_claim). Same substring-poisoning class as the reranker bug fixed
    // in the same week — descriptions are prose and must never be treated as field names.
    .filter((tool) => Object.keys((tool.inputSchema || {}).properties || {})
      .some((field) => /^(chatHistory|conversationWindow|messages|turns|transcript)$/i.test(field)))
    .map((tool) => tool.name)
    .sort();
  return {
    _generated: 'node scripts/export-directory-manifest.js — do not hand-edit',
    _why: 'The declared tool list must equal the shipped tool list; see the module docstring.',
    toolCount: names.length,
    tools: names,
    conversationDataTools: conversationTools,
    dataHandling: {
      conversationExcerptsStored: conversationTools.length > 0,
      statement: conversationTools.length > 0
        ? 'Conversation excerpts (raw prior messages, not summaries) are sent to and stored by ThumbGate when these tools are called, so feedback can be attributed to the action that earned it.'
        : 'No tool accepts conversation excerpts.',
      storedAt: '~/.thumbgate (local to the operator machine) unless a hosted API key is configured',
      userControl: 'View: thumbgate dashboard / GET /v1/search. Delete: remove ~/.thumbgate/feedback-log.jsonl and memory-log.jsonl, or DELETE the entries via the dashboard.',
    },
  };
}

async function main(argv) {
  const tools = await liveTools();
  const manifest = buildManifest(tools);
  const serialized = `${JSON.stringify(manifest, null, 2)}\n`;

  if (argv.includes('--check')) {
    let committed;
    try {
      committed = fs.readFileSync(OUT_PATH, 'utf8');
    } catch {
      process.stderr.write(`directory manifest missing at ${OUT_PATH}; run: npm run manifest:export\n`);
      return 1;
    }
    if (committed !== serialized) {
      process.stderr.write('Directory manifest is STALE — the live server no longer matches the declared list.\n'
        + `  live tools: ${manifest.toolCount}\n  run: npm run manifest:export, then update the directory listing to match.\n`);
      return 1;
    }
    process.stdout.write(`OK: declared list matches the live server (${manifest.toolCount} tools)\n`);
    return 0;
  }

  fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
  fs.writeFileSync(OUT_PATH, serialized);
  process.stdout.write(`Wrote ${manifest.toolCount} tools -> ${path.relative(process.cwd(), OUT_PATH)}\n`);
  if (manifest.conversationDataTools.length) {
    process.stdout.write(`  conversation-data tools (must be disclosed): ${manifest.conversationDataTools.join(', ')}\n`);
  }
  return 0;
}

module.exports = { liveTools, buildManifest, OUT_PATH, main };

if (require.main && require.main.filename === module.filename) {
  main(process.argv.slice(2)).then((code) => process.exit(code)).catch((err) => {
    process.stderr.write(`export-directory-manifest: ${err.message}\n`);
    process.exit(2);
  });
}
