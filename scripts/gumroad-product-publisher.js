#!/usr/bin/env node
/**
 * Gumroad Product Publisher
 * 
 * Automates the full Gumroad product creation lifecycle:
 * 1. Reads a product draft from ~/Documents/AI-Agent-Sync/Email-Drafts/
 * 2. Generates PDF + Markdown content
 * 3. Uses BrowserOS neo (Playwright + CDP) to create/publish on Gumroad
 * 4. Tracks the product in a local database
 * 5. Generates social media drafts for 10 platforms
 *
 * Stolen FORMAT from: autonomous-execution-mandate + email-triage
 * Never vendor Gumroad CLI — implement browser automation locally
 */

const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');

const DRAFTS_DIR = path.join(require('os').homedir(), 'Documents', 'AI-Agent-Sync', 'Projects', 'ThumbGate', 'Email-Drafts');
const PRODUCTS_DB = path.join(require('os').homedir(), 'Documents', 'AI-Agent-Sync', 'Projects', 'ThumbGate', 'Gumroad-Products', 'products.json');
const CDP_URL = 'http://localhost:9111';

// 10 platforms for social media draft generation
const PLATFORMS = [
  'linkedin', 'x', 'skool', 'bigger_pockets', 'reddit',
  'zyvop', 'hn', 'bluesky', 'threads', 'devto'
];

/**
 * Read a product draft from a .md file.
 * @param {string} filePath - Path to the draft .md file
 * @returns {object} Parsed product metadata and content
 */
function readDraft(filePath) {
  const content = fs.readFileSync(filePath, 'utf8');
  const frontmatterMatch = content.match(/^---\n([\s\S]*?)\n---\n/);
  let meta = {};
  let body = content;
  
  if (frontmatterMatch) {
    const fm = frontmatterMatch[1];
    body = content.substring(frontmatterMatch[0].length);
    fm.split('\n').forEach(line => {
      const [key, ...rest] = line.split(':');
      if (key) meta[key.trim()] = rest.join(':').trim();
    });
  }
  
  // Extract description section
  const descMatch = body.match(/## Description\n([\s\S]*?)(?=\n###|$)/);
  const description = descMatch ? descMatch[1].trim() : '';
  
  // Extract table of contents
  const tocMatch = body.match(/### TABLE OF CONTENTS:\n([\s\S]*?)(?=\n###|---)/);
  const toc = tocMatch ? tocMatch[1].trim() : '';
  
  return {
    title: meta.title || 'Untitled Product',
    description,
    price: meta.price || '$0.99',
    tags: meta.tags || '',
    content: body,
    toc,
    date: meta.date || new Date().toISOString().split('T')[0],
    filePath: path.basename(filePath),
  };
}

/**
 * Generate PDF content from the draft.
 * @param {object} draft - Parsed draft object
 * @param {string} outputPath - Output PDF path
 */
async function generatePDF(draft, outputPath) {
  const { chromium } = require('playwright');
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage();
  
  const html = `
<!DOCTYPE html>
<html><head><meta charset="utf-8">
<style>
body { font-family: -apple-system, sans-serif; max-width: 600px; margin: 0 auto; padding: 40px; line-height: 1.6; }
h1 { color: #ff90e8; font-size: 24px; }
h2 { color: #333; border-bottom: 1px solid #eee; padding-bottom: 5px; margin-top: 30px; }
h3 { color: #666; margin-top: 20px; }
code { background: #f5f5f5; padding: 2px 6px; border-radius: 3px; }
blockquote { border-left: 3px solid #ccc; padding-left: 15px; margin: 0; color: #666; }
pre { background: #f5f5f5; padding: 15px; border-radius: 5px; overflow-x: auto; }
.tag { display: inline-block; background: #ff90e8; color: white; padding: 2px 8px; border-radius: 3px; font-size: 12px; }
</style></head><body>
<h1>${draft.title}</h1>
<blockquote>${draft.subtitle || draft.description.substring(0, 200)}</blockquote>
${draft.description}
<h2>Table of Contents</h2>
<pre>${draft.toc || draft.content.substring(0, 500)}</pre>
<p><span class="tag">Tags</span> ${draft.tags}</p>
<p><span class="tag">Price</span> ${draft.price}</p>
<p><span class="tag">Format</span> PDF + Markdown + JSON schema</p>
<hr>
<p><small>Generated by ThumbGate Gumroad Publisher • https://thumbgate.ai</small></p>
</body></html>`;
  
  await page.setContent(html, { waitUntil: 'networkidle' });
  await page.pdf({ path: outputPath, format: 'A4', printBackground: true });
  await browser.close();
}

/**
 * Create a product on Gumroad using browser automation.
 * @param {object} draft - Parsed draft object
 * @param {string} pdfPath - Path to the PDF file
 */
async function createGumroadProduct(draft, pdfPath) {
  const browser = await chromium.connectOverCDP(CDP_URL);
  const ctx = (await browser.contexts())[0];
  const pages = await ctx.pages();
  
  // Find or create Gumroad page
  let gumPage = pages.find(p => p.url().includes('gumroad.com'));
  if (!gumPage) {
    gumPage = await ctx.newPage();
  }
  await gumPage.goto('https://gumroad.com/products/new', { waitUntil: 'networkidle' });
  
  await gumPage.waitForTimeout(2000);
  
  // Click "Digital product"
  try {
    await gumPage.click('button:has-text("Digital product")', { timeout: 10000 });
    console.log('✓ Clicked Digital product');
    await gumPage.waitForTimeout(1500);
  } catch(e) { /* already selected */ }
  
  // Fill product name
  const inputs = await gumPage.$$('input[type="text"]');
  if (inputs.length >= 2) {
    await inputs[0].fill(draft.title);
    console.log('✓ Filled name:', draft.title);
    
    // Parse price (remove $ and cents)
    const priceNum = parseFloat(draft.price.replace(/[$,]/g, ''));
    const priceStr = priceNum >= 0.99 ? priceNum.toFixed(2) : '0.99';
    await inputs[1].fill(priceStr);
    console.log('✓ Filled price: $' + priceStr);
  }
  
  // Fill description (if Add detail is available)
  try {
    const addDetailBtn = await gumPage.$('button:has-text("Add detail")');
    if (addDetailBtn && await addDetailBtn.isVisible()) {
      await addDetailBtn.click();
      await gumPage.waitForTimeout(2000);
    }
    
    await gumPage.evaluate((desc) => {
      const editable = document.querySelector('[contenteditable="true"]');
      if (editable) {
        editable.textContent = desc;
        editable.dispatchEvent(new Event('input', { bubbles: true }));
        editable.dispatchEvent(new Event('blur', { bubbles: true }));
        return true;
      }
      return false;
    }, draft.description.substring(0, 3000));
  } catch(e) { console.log('  Description:', e.message); }
  
  // Click "Next: Customize" / "Save and continue"
  try {
    await gumPage.click('button:has-text("Next: Customize")', { timeout: 10000 });
    console.log('✓ Clicked Next: Customize');
    await gumPage.waitForLoadState('networkidle', { timeout: 15000 });
    await gumPage.waitForTimeout(3000);
  } catch(e) {
    console.log('Next:', e.message);
  }
  
  // Upload content file
  if (gumPage.url().includes('/edit')) {
    try {
      await gumPage.click('button:has-text("Add version")', { timeout: 5000 }).catch(() => {});
      const fileInput = await gumPage.$('input[type="file"]');
      if (fileInput) {
        await fileInput.setInputFiles(pdfPath);
        console.log('✓ Uploaded PDF');
        await gumPage.waitForTimeout(3000);
      }
    } catch(e) { console.log('  Upload:', e.message); }
    
    // Save and publish (Gumroad flow: "Save and continue" on Product tab -> "Publish and continue" on Content tab)
    for (const stepLabel of ['Save and continue', 'Publish and continue', 'Save changes']) {
      try {
        const btn = await gumPage.$(`button:has-text("${stepLabel}")`);
        if (btn) {
          await btn.click({ force: true, timeout: 10000 });
          console.log(`✓ Clicked ${stepLabel}`);
          await gumPage.waitForTimeout(3000);
        }
      } catch (e) {
        console.log(`  Step (${stepLabel}):`, e.message);
      }
    }
  }
  
  const productUrl = gumPage.url();
  const shareUrls = await gumPage.evaluate(() => 
    Array.from(document.querySelectorAll('a[href*="/l/"]'))
      .map(a => a.href).filter(h => h.includes('/l/'))
  );
  
  await browser.close();
  
  return {
    productUrl: shareUrls[0] || productUrl,
    editUrl: productUrl,
  };
}

/**
 * Update the local product database.
 */
function trackProduct(draft, gumroadUrls) {
  const raw = fs.existsSync(PRODUCTS_DB)
    ? JSON.parse(fs.readFileSync(PRODUCTS_DB, 'utf8'))
    : { products: [], metadata: { created: new Date().toISOString().slice(0, 10), totalPublished: 0, totalRevenue: 0 } };
  const list = Array.isArray(raw) ? raw : (Array.isArray(raw.products) ? raw.products : []);

  const cleanUrl = (gumroadUrls.productUrl || '').split('?')[0];
  const product = {
    title: draft.title,
    price: draft.price,
    tags: draft.tags,
    date: draft.date,
    status: 'published',
    gumroadUrl: cleanUrl,
    editUrl: gumroadUrls.editUrl,
    productId: cleanUrl.match(/\/l\/([a-zA-Z0-9_-]+)/)?.[1] || '',
  };

  const existingIdx = list.findIndex((p) => p.productId && p.productId === product.productId);
  if (existingIdx >= 0) {
    list[existingIdx] = product;
  } else {
    list.push(product);
  }
  const out = Array.isArray(raw)
    ? { products: list, metadata: { updated: new Date().toISOString(), totalPublished: list.length, totalRevenue: 0 } }
    : { ...raw, products: list, metadata: { ...(raw.metadata || {}), updated: new Date().toISOString(), totalPublished: list.length } };
  fs.mkdirSync(path.dirname(PRODUCTS_DB), { recursive: true });
  fs.writeFileSync(PRODUCTS_DB, JSON.stringify(out, null, 2));
  console.log('✓ Product tracked in local database');
}

/**
 * Generate 3 social media drafts per platform for today.
 */
function generateSocialDrafts(draft) {
  const today = new Date().toISOString().split('T')[0];
  let count = 0;
  
  for (const platform of PLATFORMS) {
    for (let i = 0; i < 3; i++) {
      const fileName = `${today}-${platform}-monetize-thumbgate-${i + 1}.md`;
      const filePath = path.join(DRAFTS_DIR, fileName);
      
      const content = `#ThumbGate\n\nNew micro-ebook on ${platform}:\n\n${draft.title}\n\n${draft.description.substring(0, 200)}...\n\nGet it at: ${draft.price} — https://iganapolsky.gumroad.com\n`;
      
      fs.writeFileSync(filePath, content);
      count++;
    }
  }
  console.log(`✓ Generated ${count} social media drafts for ${PLATFORMS.length} platforms`);
}

/**
 * Main execution.
 */
async function main() {
  const args = process.argv.slice(2);
  let draftPath = args[0];
  
  if (!draftPath) {
    // Find the latest Gumroad draft
    const files = fs.readdirSync(DRAFTS_DIR)
      .filter(f => f.includes('gumroad') && f.includes('draft'))
      .sort()
      .reverse();
    
    if (files.length === 0) {
      console.error('No Gumroad draft found. Create one first.');
      process.exit(1);
    }
    
    draftPath = path.join(DRAFTS_DIR, files[0]);
  }
  
  console.log('📄 Reading draft:', path.basename(draftPath));
  const draft = readDraft(draftPath);
  console.log('   Title:', draft.title);
  console.log('   Price:', draft.price);
  console.log('   Tags:', draft.tags);
  
  // Generate PDF
  const pdfPath = path.join(DRAFTS_DIR, `${path.basename(draftPath, '.md')}.pdf`);
  console.log('\n📄 Generating PDF...');
  await generatePDF(draft, pdfPath);
  console.log('✓ PDF created:', pdfPath);
  
  // Create on Gumroad
  console.log('\n🍮 Publishing to Gumroad...');
  const gumroadUrls = await createGumroadProduct(draft, pdfPath);
  console.log('   Product URL:', gumroadUrls.productUrl);
  console.log('   Edit URL:', gumroadUrls.editUrl);
  
  // Track product
  console.log('\n📊 Tracking product...');
  trackProduct(draft, gumroadUrls);
  
  // Generate social drafts
  console.log('\n📱 Generating social media drafts...');
  generateSocialDrafts(draft);
  
  console.log('\n✅ Done! Product published and tracked.');
  console.log(`   Gumroad: ${gumroadUrls.productUrl}`);
  console.log(`   Products DB: ${PRODUCTS_DB}`);
}

main().catch(e => {
  console.error('Error:', e.message);
  process.exit(1);
});
