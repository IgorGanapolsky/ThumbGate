// scripts/multi-variant-explorer.js
'use strict';

/**
 * Multi-Variant Exploration — Founder Blind Spots steal.
 *
 * Generates N variant implementations from a single task, runs each through
 * the Isolated Verifier, and ranks by quality + score.
 *
 * Stolen from: "AI as a Force Multiplier for Creatives" (DgX3XqhIhas)
 */

const { execSync } = require('node:child_process');
const path = require('node:path');
const fs = require('node:fs');

// Discard criteria — auto-reject variants that trigger any of these
const DISCARD_CRITERIA = [
  { name: 'block_lesson', check: (v) => v.lessons.some((l) => l.severity === 'BLOCK'), reason: 'Triggered BLOCK lesson' },
  { name: 'verification_failures', check: (v) => v.failedChecks > 2, reason: 'More than 2 verification failures' },
  { name: 'latency_budget', check: (v) => v.latency > 2000, reason: 'Latency exceeds 2x budget' },
  { name: 'security_finding', check: (v) => v.auditFindings.some((f) => f.severity === 'critical'), reason: 'Critical security finding' },
];

/**
 * Generate N variant implementations from a task description.
 *
 * @param {Object} opts
 * @param {string} opts.task - Problem statement
 * @param {number} opts.count - Number of variants to generate (3-10)
 * @param {Array<string>} opts.models - Open-weights model IDs to cycle through
 * @param {string} opts.gate - Verification gate level: 'strict' | 'standard' | 'relaxed'
 */
function exploreVariants(opts) {
  const { task, count = 5, models = ['deepseek-7b-chat', 'glm-4-9b-chat', 'qwen3-4b'], gate = 'strict' } = opts;

  console.log(`# Multi-Variant Exploration`);
  console.log(`Task: ${task.slice(0, 80)}...`);
  console.log(`Variants: ${count} | Models: ${models.join(', ')} | Gate: ${gate}`);
  console.log(`\n---`);

  const variants = [];
  for (let i = 0; i < count; i++) {
    const model = models[i % models.length];
    variants.push({
      id: `v${i + 1}`,
      model,
      task,
      // In production, this would call the model to generate implementation
      // For now, we stub with placeholders
      implementation: `{{generated by ${model}}}`,
      quality: Math.floor(Math.random() * 30) + 70, // 70-100
      failedChecks: Math.floor(Math.random() * 3), // 0-2
      latency: Math.floor(Math.random() * 1500) + 200, // ms
      auditFindings: [],
      lessons: [],
    });
  }

  // Score + rank
  const scored = variants.map((v) => {
    const score = v.quality * 0.6 - v.failedChecks * 15 - (v.latency / 50);
    const discarded = DISCARD_CRITERIA.find((c) => c.check(v));
    return { ...v, score: Math.round(score), discarded: discarded ? discarded.reason : null };
  });

  scored.sort((a, b) => b.score - a.score);

  return scored;
}

function main() {
  const args = process.argv.slice(2);
  const taskIdx = args.indexOf('--task');
  const countIdx = args.indexOf('--count');
  const gateIdx = args.indexOf('--gate');
  const modelIdx = args.indexOf('--model');

  if (taskIdx === -1) {
    console.log('Usage: multi-variant-explorer.js --task "<description>" [--count N] [--gate strict] [--model deepseek-7b]');
    console.log('\nExample:');
    console.log('  node scripts/multi-variant-explorer.js --task "Rate limiter with burst capacity" --count 5');
    process.exit(0);
  }

  const task = args.slice(taskIdx + 1, countIdx === -1 ? args.length : countIdx).join(' ');
  const count = countIdx !== -1 ? parseInt(args[countIdx + 1]) : 5;
  const gate = gateIdx !== -1 ? args[gateIdx + 1] : 'strict';

  const variants = exploreVariants({ task, count, gate });

  console.log('\n=== Variant Ranking ===\n');
  for (const v of variants) {
    const status = v.discarded ? `❌ DISCARDED (${v.discarded})` : `✅ PASS GATES`;
    console.log(`${status}  ${v.id} [${v.model}]  score=${v.score}/100  latency=${v.latency}ms  failed=${v.failedChecks}`);
  }

  const winner = variants.find((v) => !v.discarded);
  if (winner) {
    console.log(`\n🏆 Winner: ${winner.id} (${winner.model}) — score ${winner.score}/100`);
  } else {
    console.log(`\n💀 All variants discarded. No viable implementation.`);
  }
}

if (require.main === module) {
  main();
}

module.exports = { exploreVariants, DISCARD_CRITERIA };
