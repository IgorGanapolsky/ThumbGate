#!/usr/bin/env node
'use strict';

// Status-line thumb counts: only feedback a person gave, only for the project
// the status line is rendered in. Prints {"up":N,"down":N,"label":"this project"}.
//
// Two stores can hold a project's thumbs: the project's own feedback dir, and the
// global ~/.thumbgate store, where MCP capture_feedback calls land because the MCP
// server does not run in the project directory. Global rows belong to this
// project when they carry its project key, or only scope.projectId equal to the
// project folder name.
const fs = require('node:fs');
const path = require('node:path');
const { readProjectRows } = require('./project-catalog');
const { resolveLocalProject, hash } = require('./project-identity');
const { resolveProjectDir, resolveFeedbackDir, getHomeDir } = require('./feedback-paths');
const { isCountedHumanFeedback, isLegacyMcpCapture } = require('./human-feedback');
const { readInjections, computeLessonEffect } = require('./lesson-effect');

function normalizeSignal(entry) {
  const raw = String(entry.signal || entry.feedback || '').toLowerCase();
  if (raw === 'positive' || raw === 'up' || raw === 'thumbs_up') return 'up';
  if (raw === 'negative' || raw === 'down' || raw === 'thumbs_down') return 'down';
  return null;
}

// The agent records a thumb within seconds of the message that carried it.
const CORROBORATION_MS = 90 * 1000;

function rowTime(row) {
  const at = Date.parse(row.timestamp || row.createdAt || '');
  return Number.isFinite(at) ? at : null;
}

function isScrapedHumanThumb(row) {
  if (String(row.reviewOrigin || '').toLowerCase() !== 'human') return false;
  const tags = Array.isArray(row.tags) ? row.tags : [];
  return tags.includes('claude-history-sync');
}

// "[Eci.Psn.StockService] Igor: thumbs up": the prefix names the project the thumb was given in.
function contextProjectPrefix(row) {
  const match = String(row.context || '').match(/^\s*\[([^\]]{1,80})\]/);
  return match ? match[1].trim().toLowerCase() : null;
}

// Only a thumbs-up can be auto-made this way: "found a successful pattern" is the sync's own guess, and a
// positive row with no text that the system logged as no-action names nothing. A distilled failure quotes the
// person's own message, so it stays.
function isAutoGenerated(row) {
  if (normalizeSignal(row) !== 'up') return false;
  const context = String(row.context || '').trim();
  if (!context) return String(row.actionType || '').toLowerCase() === 'no-action';
  return /^history-aware distillation found a successful pattern/i.test(context);
}

// Rows that were written but are not a person's thumb (a test probe, a script's capture). Nothing is deleted or
// rewritten: one JSON line per row id in not-counted-feedback.jsonl, next to the feedback log, is read here and the
// row is left out of every count. Written by scripts/not-a-thumb.js.
const NOT_COUNTED_FILE = 'not-counted-feedback.jsonl';

function readNotCounted(dirs) {
  const ids = new Map();
  for (const dir of dirs) {
    let text = '';
    // Only a missing ledger means "nothing marked". Any other read error (permissions, a directory) must surface,
    // or rows the ledger excludes would be counted and a wrong total published.
    try { text = fs.readFileSync(path.join(dir, NOT_COUNTED_FILE), 'utf8'); } catch (error) {
      if (error && error.code === 'ENOENT') continue;
      throw error;
    }
    for (const line of text.split('\n')) {
      if (!line.trim()) continue;
      try {
        const entry = JSON.parse(line);
        if (entry && entry.id) ids.set(String(entry.id), entry.reason || '');
      } catch (_) { /* a damaged line hides nothing */ }
    }
  }
  return ids;
}

function collectHumanRows(options = {}) {
  const env = options.env || process.env;
  const cwd = options.cwd || process.cwd();
  const projectDir = resolveProjectDir({ cwd, env, projectDir: options.projectDir });
  const feedbackDir = resolveFeedbackDir({ projectDir, env });
  const { projectKey } = resolveLocalProject(projectDir);
  const projectName = path.basename(projectDir);
  // readProjectRows maps a row that only names a project in scope.projectId to this legacy key.
  const aliasKey = `legacy_${hash(projectName)}`;
  const globalDir = path.join(getHomeDir({ env }), '.thumbgate');

  const seen = new Set();
  const mineRows = [];
  // Rows read but kept out of the headline. Nothing is deleted or rewritten; they are only not counted.
  const excluded = { otherProject: 0, unassignedNoEvidence: 0, autoGenerated: 0, markedNotThumb: 0 };
  const excludedRows = [];
  const drop = (rule, row) => { excluded[rule] += 1; excludedRows.push({ id: row.id || null, rule, signal: normalizeSignal(row), timestamp: row.timestamp || null }); };
  const ownDir = path.resolve(feedbackDir);
  // THUMBGATE_FEEDBACK_DIR can point the resolved dir at the shared store, which
  // would hide this project's own log. The project's own .thumbgate folder is always read too.
  const projectLocalDir = path.resolve(projectDir, '.thumbgate');
  const ownDirs = new Set([ownDir, projectLocalDir]);
  const notCounted = readNotCounted([...ownDirs, path.resolve(globalDir)]);
  for (const dir of new Set([ownDir, projectLocalDir, path.resolve(globalDir)])) {
    // Rows written before project tracking carry no key. In the project's own
    // feedback dir they are this project's; in the shared global store they are not.
    const ownsUnassigned = ownDirs.has(dir) && dir !== path.resolve(globalDir);
    for (const row of readProjectRows(dir, 'feedback-log.jsonl', {})) {
      const mine = row.projectKey === projectKey || row.projectKey === aliasKey
        || (ownsUnassigned && row.projectKey === 'unassigned');
      if (!mine) continue;
      if (row.id) {
        if (seen.has(row.id)) continue;
        seen.add(row.id);
      }
      if (row.id && notCounted.has(String(row.id))) {
        if (normalizeSignal(row)) drop('markedNotThumb', row);
        continue;
      }
      // A thumb given in another project never counts here, whatever key it carries.
      const prefix = contextProjectPrefix(row);
      if (prefix && prefix !== projectName.toLowerCase()) {
        if (normalizeSignal(row)) drop('otherProject', row);
        continue;
      }
      mineRows.push({ row, unassigned: row.projectKey === 'unassigned' });
    }
  }

  // A thumb the history sync scraped from the person's own message is evidence
  // that the person gave one at that moment. An MCP capture that an older server
  // labelled automated counts when such evidence sits next to it; without it the
  // row is a lesson the agent logged on its own judgment.
  const scraped = { up: [], down: [] };
  for (const { row } of mineRows) {
    const signal = normalizeSignal(row);
    const at = rowTime(row);
    if (signal && at !== null && isScrapedHumanThumb(row)) scraped[signal].push(at);
  }
  const corroborated = (row) => {
    const signal = normalizeSignal(row);
    const at = rowTime(row);
    return Boolean(signal) && at !== null && scraped[signal].some((t) => Math.abs(t - at) <= CORROBORATION_MS);
  };

  // A row written before project tracking carries no key, so it proves nothing about
  // which project it belongs to. It counts only when the row itself shows the person
  // typed the thumb (the user-prompt hook tag, or a history-sync scrape beside it).
  // Text in the context ("Explicit user thumbs-up") is the agent's own wording and proves nothing.
  const hasPersonEvidence = (row) => {
    const tags = Array.isArray(row.tags) ? row.tags : [];
    return tags.includes('user-prompt-thumbs') || corroborated(row);
  };
  const counted = [];
  for (const { row, unassigned } of mineRows) {
    if (!normalizeSignal(row)) continue;
    if (!(isCountedHumanFeedback(row) || (isLegacyMcpCapture(row) && corroborated(row)))) continue;
    // A learning the history sync distilled on its own, or a row with no text at all, is never a thumb.
    if (isAutoGenerated(row)) {
      drop('autoGenerated', row);
      continue;
    }
    if (unassigned && !hasPersonEvidence(row)) {
      drop('unassignedNoEvidence', row);
      continue;
    }
    counted.push(row);
  }
  return { rows: counted, projectKey, projectName, projectDir, excluded, excludedRows, injectionDirs: [...ownDirs] };
}

function computeHumanCounts(options = {}) {
  const { rows, projectName, excluded, injectionDirs } = collectHumanRows(options);
  let up = 0;
  let down = 0;
  let latestDown = null;
  const downs = [];
  for (const row of rows) {
    const signal = normalizeSignal(row);
    if (signal === 'up') up += 1;
    if (signal === 'down') {
      down += 1;
      const at = rowTime(row);
      if (at !== null) downs.push({ at, tags: row.tags });
      if (at !== null && (!latestDown || at > latestDown.at)) latestDown = { at, row };
    }
  }
  const lessonEffect = computeLessonEffect(readInjections(injectionDirs), downs);
  return { up, down, label: 'this project', project: projectName, latestDown: describeLatestDown(latestDown), notCounted: excluded.unassignedNoEvidence, lessonEffect };
}

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

// The reader's own clock, 12-hour: "Nov 19, 3:37 PM". Built by hand because
// toLocaleString puts a narrow no-break space before AM/PM on newer ICU builds.
function formatStamp(ms) {
  const d = new Date(ms);
  const hour = d.getHours() % 12 || 12;
  const minute = String(d.getMinutes()).padStart(2, '0');
  return `${MONTHS[d.getMonth()]} ${d.getDate()}, ${hour}:${minute} ${d.getHours() < 12 ? 'AM' : 'PM'}`;
}

function describeLatestDown(found) {
  if (!found) return null;
  const { at, row } = found;
  const raw = String(row.whatWentWrong || row.whatToChange || row.context || '').replace(/\s+/g, ' ').trim();
  return {
    id: row.id || null,
    timestamp: new Date(at).toISOString(),
    label: `Latest mistake ${formatStamp(at)}`,
    text: raw.length > 60 ? `${raw.slice(0, 57)}...` : raw,
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(__filename)) {
  try {
    process.stdout.write(JSON.stringify(computeHumanCounts()));
  } catch (_) {
    process.exit(0);
  }
}

// The one counter, applied to a stats payload another code path built (analyzeFeedback, the dashboard totals):
// the thumb totals come from computeHumanCounts and nothing else; every other field is left as it was.
function applyHumanCounts(stats = {}, options = {}) {
  const { up, down } = computeHumanCounts(options);
  const total = up + down;
  const rate = total ? up / total : 0;
  const out = {
    ...stats,
    totalPositive: up,
    totalNegative: down,
    total,
    approvalRate: rate,
  };
  // The lifetime window repeats the same two totals, so it follows them. The short recent windows and the
  // per-skill and per-tag buckets are trends, not the headline thumb count, and keep what analyzeFeedback built.
  if (stats.windows && stats.windows.lifetime) {
    out.windows = { ...stats.windows, lifetime: { ...stats.windows.lifetime, total, rate } };
  }
  return out;
}

module.exports = { computeHumanCounts, collectHumanRows, applyHumanCounts, NOT_COUNTED_FILE };
