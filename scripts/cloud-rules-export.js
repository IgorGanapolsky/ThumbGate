'use strict';

// Cloud agents never run ThumbGate's hooks. A claude.ai project, cloud Claude Code, Codex cloud or a Cursor background
// agent works in a fresh clone of the repo, so the gates in the local feedback store never fire on its turns. What those
// agents do read is instruction files checked into the repo: Claude Code loads every `.claude/rules/*.md`, and Codex,
// Cursor and most others read AGENTS.md.
//
// `thumbgate export-rules` writes this project's learned rules (auto-promoted gates, claim rules and prevention rules)
// into those files, so a cloud agent follows them by reading. The output has no timestamp, so the file changes only
// when the rules change, and `thumbgate session-start` refreshes a file that was exported before. Lesson prose stays
// out unless --include-lessons is passed, and every line goes through secret and PII redaction, because these files are
// committed.

const fs = require('node:fs');
const path = require('node:path');

const MARKER = '<!-- generated by `npx thumbgate export-rules`; do not edit by hand -->';
const BLOCK_START = '<!-- thumbgate:rules:start -->';
const BLOCK_END = '<!-- thumbgate:rules:end -->';
const CLAUDE_RULES_FILE = path.join('.claude', 'rules', 'thumbgate.md');
const AGENTS_FILE = 'AGENTS.md';
const TARGETS = ['claude', 'agents', 'all'];
const MAX_ITEMS = 40;

function safe(fn, fallback) {
  try { return fn(); } catch { return fallback; }
}

function clean(text, max = 240) {
  let out = String(text == null ? '' : text).replace(/\s+/g, ' ').trim();
  out = out.replace(/\/(?:Users|home)\/[^/\s`'"]+/g, '~');
  const { redactPii } = require('./pii-scanner'); // redacts secrets first, then emails, phones and the like
  out = safe(() => redactPii(out), out);
  return out.length > max ? `${out.slice(0, max - 1)}…` : out;
}

function code(text) {
  const t = clean(text, 200).replace(/`/g, "'");
  return t ? `\`${t}\`` : '';
}

function isLive(gate, nowMs) {
  if (!gate || gate.active === false) return false;
  if (!gate.expiresAt) return true;
  const at = Date.parse(gate.expiresAt);
  return !Number.isFinite(at) || at > nowMs;
}

/** Read the learned rules for one feedback dir. Built-in gates ship with the package and are left out. */
function collectRules({ feedbackDir, cwd = process.cwd(), includeLessons = false, now = Date.now() } = {}) {
  const { loadAutoGates } = require('./auto-promote-gates');
  const claimRules = require('./claim-gate-rules');
  const auto = safe(() => loadAutoGates({ feedbackDir }), { gates: [] });
  const gates = (auto.gates || [])
    .filter((g) => isLive(g, now) && (g.pattern || g.message))
    // The "(N occurrences in 30 days)" tail changes on every fire; leave it out so the file only changes with the rule.
    .map((g) => ({ id: String(g.id || ''), action: String(g.action || 'warn'), pattern: g.pattern || '', message: String(g.message || '').replace(/\s*\((?:\d+ occurrences|manual)[^)]*\)\s*$/, '') }))
    .sort((a, b) => a.id.localeCompare(b.id));

  const claims = (safe(() => claimRules.readRules(feedbackDir), { rules: [] }).rules || [])
    .map((r) => ({ id: String(r.id || r.key || ''), message: r.message || '' }))
    .filter((r) => r.message)
    .sort((a, b) => a.id.localeCompare(b.id));

  // `thumbgate rules` writes <cwd>/.thumbgate/prevention-rules.md; the API writes it into the feedback dir.
  const rulesMd = [path.join(feedbackDir, 'prevention-rules.md'), path.join(cwd, '.thumbgate', 'prevention-rules.md')]
    .map((p) => safe(() => fs.readFileSync(p, 'utf8'), ''))
    .find(Boolean) || '';
  // Each section is "## <domain>" then "- Rule: ..." lines; counts and weights change daily, so only rules are kept.
  const prevention = rulesMd.split(/^## /m).slice(1).flatMap((section) => {
    const lines = section.trim().split('\n').map((l) => l.trim());
    const title = lines[0] || '';
    return lines.filter((l) => /^[-*]\s*rule:/i.test(l)).map((l) => ({ title, detail: l.replace(/^[-*]\s*rule:\s*/i, '') }));
  }).filter((r) => r.title && r.detail);

  let lessons = [];
  if (includeLessons) {
    const { exploreLessons } = require('./explore-subcommands');
    lessons = (safe(() => exploreLessons({ feedbackDir, limit: MAX_ITEMS, json: true }), { lessons: [] }).lessons || [])
      .map((l) => ({ signal: String(l.signal || ''), context: l.context || '' }))
      .filter((l) => l.context);
  }
  return { gates, claims, prevention, lessons };
}

function renderMarkdown(model, { heading = '#' } = {}) {
  const h2 = `${heading}#`;
  const out = [MARKER, '', `${heading} ThumbGate rules for this project`, ''];
  out.push('These rules come from thumbs-down feedback on earlier agent work here. On a machine with ThumbGate hooks they are enforced before each tool call. In a cloud session no hook runs, so you enforce them yourself: before each tool call, check it against the blocked and ask-first lists, and before stating a fact, check it against the claim rules. If a blocked pattern matches, do not run the call; say which rule stopped you.');
  out.push('');
  const block = model.gates.filter((g) => g.action === 'block');
  const ask = model.gates.filter((g) => g.action !== 'block');
  const gateLine = (g) => {
    const pattern = g.pattern ? `${code(g.pattern)} (regex on the command or tool input)` : '';
    const msg = clean(g.message);
    return `- ${[pattern, msg].filter(Boolean).join(': ')}`;
  };
  out.push(`${h2} Blocked: do not run`, '');
  out.push(...(block.length ? block.slice(0, MAX_ITEMS).map(gateLine) : ['_None yet._']), '');
  out.push(`${h2} Ask the user first`, '');
  out.push(...(ask.length ? ask.slice(0, MAX_ITEMS).map(gateLine) : ['_None yet._']), '');
  out.push(`${h2} Claims that need a check this turn`, '');
  out.push(...(model.claims.length ? model.claims.slice(0, MAX_ITEMS).map((c) => `- ${clean(c.message, 400)}`) : ['_None yet._']), '');
  out.push(`${h2} Learned rules`, '');
  out.push(...(model.prevention.length
    ? model.prevention.slice(0, MAX_ITEMS).map((r) => `- ${clean(r.detail)} (${clean(r.title, 60)})`)
    : ['_None yet._']), '');
  if (model.lessons.length) {
    out.push(`${h2} Recent lessons`, '');
    for (const l of model.lessons.slice(0, MAX_ITEMS)) {
      const mark = /up|positive/i.test(l.signal) ? 'Keep doing' : 'Avoid';
      out.push(`- ${mark}: ${clean(l.context)}`);
    }
    out.push('');
  }
  out.push(`_${model.gates.length} gates, ${model.claims.length} claim rules, ${model.prevention.length} learned rules. Refresh with \`npx thumbgate export-rules\`._`);
  return `${out.join('\n')}\n`;
}

function writeIfChanged(file, content) {
  const before = safe(() => fs.readFileSync(file, 'utf8'), null);
  if (before === content) return false;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  return true;
}

function mergeAgentsBlock(existing, body) {
  const block = `${BLOCK_START}\n${body.trimEnd()}\n${BLOCK_END}\n`;
  if (!existing) return block;
  const start = existing.indexOf(BLOCK_START);
  const end = existing.indexOf(BLOCK_END);
  if (start !== -1 && end > start) {
    return existing.slice(0, start) + block + existing.slice(end + BLOCK_END.length).replace(/^\n/, '');
  }
  return `${existing.trimEnd()}\n\n${block}`;
}

/**
 * Write the export. target: claude (.claude/rules/thumbgate.md), agents (a marked block in AGENTS.md) or all.
 * With check: true nothing is written and `stale` lists the files that differ.
 */
function exportRules({ cwd = process.cwd(), feedbackDir, target = 'claude', output, includeLessons = false, check = false, now } = {}) {
  if (!TARGETS.includes(target)) throw new Error(`Unknown target "${target}". Use one of: ${TARGETS.join(', ')}`);
  const model = collectRules({ feedbackDir, cwd, includeLessons, now });
  const files = [];
  if (target === 'claude' || target === 'all') {
    const file = output && target === 'claude' ? path.resolve(cwd, output) : path.join(cwd, CLAUDE_RULES_FILE);
    files.push({ file, content: renderMarkdown(model) });
  }
  if (target === 'agents' || target === 'all') {
    const file = output && target === 'agents' ? path.resolve(cwd, output) : path.join(cwd, AGENTS_FILE);
    const existing = safe(() => fs.readFileSync(file, 'utf8'), '');
    files.push({ file, content: mergeAgentsBlock(existing, renderMarkdown(model, { heading: '##' })) });
  }
  const results = files.map(({ file, content }) => {
    const current = safe(() => fs.readFileSync(file, 'utf8'), null);
    const changed = current !== content;
    if (!check) writeIfChanged(file, content);
    return { path: file, changed };
  });
  return {
    ok: check ? results.every((r) => !r.changed) : true,
    check,
    files: results,
    counts: { gates: model.gates.length, claims: model.claims.length, prevention: model.prevention.length, lessons: model.lessons.length },
  };
}

/** Refresh exports that already exist (the user opted in by running export-rules once). Never creates a file. */
function refreshExistingExports({ cwd = process.cwd(), feedbackDir } = {}) {
  const refreshed = [];
  const claudeFile = path.join(cwd, CLAUDE_RULES_FILE);
  if (safe(() => fs.readFileSync(claudeFile, 'utf8').startsWith(MARKER), false)) {
    const r = exportRules({ cwd, feedbackDir, target: 'claude' });
    if (r.files[0].changed) refreshed.push(claudeFile);
  }
  const agentsFile = path.join(cwd, AGENTS_FILE);
  if (safe(() => fs.readFileSync(agentsFile, 'utf8').includes(BLOCK_START), false)) {
    const r = exportRules({ cwd, feedbackDir, target: 'agents' });
    if (r.files[0].changed) refreshed.push(agentsFile);
  }
  return refreshed;
}

module.exports = {
  MARKER,
  BLOCK_START,
  BLOCK_END,
  CLAUDE_RULES_FILE,
  TARGETS,
  collectRules,
  renderMarkdown,
  mergeAgentsBlock,
  exportRules,
  refreshExistingExports,
};
