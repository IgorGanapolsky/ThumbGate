#!/usr/bin/env node
'use strict';

/**
 * Async Confusion Review — OLAP path for post-action confusion analysis.
 *
 * Mirrors Supabase's pattern of separating OLTP (fast local) from OLAP
 * (analytical post-processing). While runConfusionPreCheck runs in <5ms
 * before each action (OLTP), this module runs AFTER actions complete
 * on batched session histories to detect recurring confusion patterns
 * and auto-generate prevention rules.
 *
 * Usage:
 *   node scripts/async-confusion-review.js --session <session-id>
 *   node scripts/async-confusion-review.js --batch
 *   node scripts/async-confusion-review.js --since "2h"
 */

const fs = require('node:fs');
const path = require('node:path');
const {
  runConfusionAsyncReview,
  generatePreventRules,
} = require('./confusion-detector');

const SESSION_HISTORY_DIR = path.join(os.homedir(), '.thumbgate', 'session-history');
const PREVENTION_RULES_DIR = path.join(__dirname, '..', '.thumbgate', 'prevention-rules');

/**
 * Review a single session's action history for confusion patterns.
 * @param {string} sessionId - Unique session identifier
 * @param {Array} actions - Session action records
 * @returns {{ findings: Array, preventionRules: Object }}
 */
function reviewSession(sessionId, actions) {
  const findings = runConfusionAsyncReview(actions);
  const rules = generatePreventRules(findings);
  return { sessionId, findings, preventionRules: rules };
}

/**
 * Batch review all sessions modified within a time window.
 * @param {number} sinceMinutes - How far back to review (default: 120 = 2h)
 * @returns {{ sessionsReviewed: number, totalFindings: number, preventionRules: Array }}
 */
function batchReview(sinceMinutes = 120) {
  const cutoff = Date.now() - sinceMinutes * 60 * 1000;
  let sessionsReviewed = 0;
  let totalFindings = 0;
  const allRules = [];

  if (!fs.existsSync(SESSION_HISTORY_DIR)) {
    return { sessionsReviewed: 0, totalFindings: 0, preventionRules: [] };
  }

  const files = fs.readdirSync(SESSION_HISTORY_DIR).filter((f) => f.endsWith('.json'));
  for (const file of files) {
    try {
      const stat = fs.statSync(path.join(SESSION_HISTORY_DIR, file));
      if (stat.mtimeMs < cutoff) continue;

      const session = JSON.parse(fs.readFileSync(path.join(SESSION_HISTORY_DIR, file), 'utf8'));
      const actions = session.actions || session.sessionActions || [];
      if (!Array.isArray(actions) || actions.length === 0) continue;

      sessionsReviewed++;
      const result = reviewSession(session.id || file, actions);
      totalFindings += result.findings.length;

      if (result.preventionRules.preventionRules.length > 0) {
        allRules.push(...result.preventionRules.preventionRules);
      }
    } catch (err) {
      // Skip malformed session files silently
    }
  }

  return { sessionsReviewed, totalFindings, preventionRules: allRules };
}

/**
 * Write a prevention rule to the prevention-rules directory.
 * Prevention rules are declarative — agents read them as config, not code.
 */
function writePreventionRule(pattern, recommendation, occurrences) {
  if (!fs.existsSync(PREVENTION_RULES_DIR)) {
    fs.mkdirSync(PREVENTION_RULES_DIR, { recursive: true });
  }

  // Sanitize filename
  const safeId = pattern.replace(/[^a-z0-9]/gi, '_').toLowerCase();
  const fileName = `confusion-${safeId}.md`;
  const filePath = path.join(PREVENTION_RULES_DIR, fileName);

  const content = `# Confused-Agent Prevention Rule

**Pattern**: ${pattern}

**Occurrences**: ${occurrences}

**Recommendation**: ${recommendation}

**Category**: confusion-detection

**Auto-generated by**: \`scripts/async-confusion-review.js\`
**DO NOT EDIT MANUALLY** — this file is regenerated from session history.
`;

  fs.writeFileSync(filePath, content, 'utf8');
  return filePath;
}

// ---------------------------------------------------------------------------
// CLI entry point
// ---------------------------------------------------------------------------

const os = require('node:os');

function runCli() {
  const args = process.argv.slice(2);
  const command = args[0] || '--batch';

  if (command === '--batch') {
    const sinceMin = parseInt(args[1]?.replace('--since', '') || '120', 10);
    const result = batchReview(sinceMin);
    console.log(JSON.stringify(result, null, 2));

    // Write prevention rules for new patterns
    for (const rule of result.preventionRules) {
      writePreventionRule(rule.pattern, rule.recommendation, rule.occurrences);
    }

    console.log(`\nReviewed ${result.sessionsReviewed} sessions, found ${result.totalFindings} confusion patterns.`);
  }

  if (command === '--session') {
    const sessionId = args[1];
    if (!sessionId) {
      console.error('Usage: node scripts/async-confusion-review.js --session <session-id>');
      process.exit(1);
    }
    const sessionFile = path.join(SESSION_HISTORY_DIR, `${sessionId}.json`);
    if (!fs.existsSync(sessionFile)) {
      console.error(`Session file not found: ${sessionFile}`);
      process.exit(1);
    }
    const session = JSON.parse(fs.readFileSync(sessionFile, 'utf8'));
    const result = reviewSession(sessionId, session.actions || []);
    console.log(JSON.stringify(result, null, 2));

    for (const rule of result.preventionRules.preventionRules) {
      writePreventionRule(rule.pattern, rule.recommendation, rule.occurrences);
    }
  }
}

if (require.main === module) {
  runCli();
}

module.exports = {
  reviewSession,
  batchReview,
  writePreventionRule,
};
