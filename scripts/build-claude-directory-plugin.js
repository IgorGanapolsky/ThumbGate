#!/usr/bin/env node
'use strict';

// Builds plugins/claude-directory/, the slim ThumbGate plugin that the Claude plugin
// directory (claude.ai/directory/manage) can scan. The repository root is not
// submittable: the directory refuses a plugin root that holds package.json, a
// lockfile, bin/, HTML, CSS, dotfiles or an unpinned `npx` launcher.
//
// The slim plugin holds only Markdown and JSON:
//   .claude-plugin/plugin.json  MCP server launched as `npx -y thumbgate@<version> serve`
//   hooks/hooks.json            PreToolUse and UserPromptSubmit through the same pinned CLI
//   skills/<name>/              the user-facing ThumbGate skills, frontmatter reduced to
//                               plain `name:` and `description:` lines
//   README.md, LICENSE, .claude-plugin/icon.png
//
// The directory accepts command hooks and local MCP servers only from Verified
// organizations, so this plugin lists once the publisher is Verified.
//
//   node scripts/build-claude-directory-plugin.js          write the folder
//   node scripts/build-claude-directory-plugin.js --check  exit 1 if it is out of date

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'plugins', 'claude-directory');
const SKILLS = [
  'thumbgate',
  'thumbgate-feedback',
  'thumbgate-guard',
  'thumbgate-rules',
  'thumbgate-doctor',
  'thumbgate-blocked',
  'thumbgate-protect',
];

function readFrontmatter(text) {
  const match = /^---\n([\s\S]*?)\n---\n?/.exec(text);
  if (!match) return { fields: {}, body: text };
  const fields = {};
  let key = null;
  for (const line of match[1].split('\n')) {
    const top = /^([A-Za-z_][\w-]*):\s*(.*)$/.exec(line);
    if (top) {
      key = top[1];
      const value = top[2].trim();
      fields[key] = value === '>' || value === '|' || value === '>-' || value === '|-' ? '' : value;
    } else if (key && /^\s+\S/.test(line) && !/^\s+-\s/.test(line)) {
      fields[key] = `${fields[key]} ${line.trim()}`.trim();
    }
  }
  return { fields, body: text.slice(match[0].length) };
}

function plainValue(value) {
  return String(value || '')
    .replace(/^["']|["']$/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function skillFiles(name) {
  const dir = path.join(ROOT, 'skills', name);
  const files = {};
  const { fields, body } = readFrontmatter(fs.readFileSync(path.join(dir, 'SKILL.md'), 'utf8'));
  const description = plainValue(fields.description);
  if (!description) throw new Error(`skills/${name}/SKILL.md has no description`);
  files[`skills/${name}/SKILL.md`] = `---\nname: ${name}\ndescription: ${description}\n---\n${body}`;
  const refs = path.join(dir, 'references');
  if (fs.existsSync(refs)) {
    for (const file of fs.readdirSync(refs).sort()) {
      if (!file.endsWith('.md')) continue;
      files[`skills/${name}/references/${file}`] = fs.readFileSync(path.join(refs, file), 'utf8');
    }
  }
  return files;
}

function expectedFiles() {
  const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
  const version = pkg.version;
  const spec = `thumbgate@${version}`;
  const json = (value) => `${JSON.stringify(value, null, 2)}\n`;

  const files = {
    '.claude-plugin/plugin.json': json({
      name: 'thumbgate',
      description: 'Pre-action checks for Claude Code. A thumbs-down becomes a prevention rule, and a PreToolUse hook checks each tool call against your rules and the default gates before it runs.',
      version,
      author: { name: 'Igor Ganapolsky', url: 'https://thumbgate.ai' },
      homepage: 'https://thumbgate.ai',
      repository: 'https://github.com/IgorGanapolsky/ThumbGate',
      license: 'MIT',
      keywords: ['guardrails', 'pretooluse', 'hooks', 'agent-safety', 'pre-action-checks'],
      icon: './.claude-plugin/icon.png',
      // npx downloads the pinned package from npm; the CLI sends usage telemetry to thumbgate.ai.
      network: { hosts: ['registry.npmjs.org', 'thumbgate.ai'] },
      mcpServers: {
        thumbgate: { command: 'npx', args: ['-y', spec, 'serve'] },
      },
    }),
    'hooks/hooks.json': json({
      hooks: {
        PreToolUse: [
          { matcher: '.*', hooks: [{ type: 'command', command: 'npx', args: ['-y', spec, 'gate-check'] }] },
        ],
        UserPromptSubmit: [
          { hooks: [{ type: 'command', command: 'npx', args: ['-y', spec, 'hook-auto-capture'] }] },
        ],
      },
    }),
    'README.md': [
      '# ThumbGate for Claude Code',
      '',
      'This folder is the ThumbGate plugin as submitted to the Claude plugin directory. It is generated by',
      '`scripts/build-claude-directory-plugin.js` from the repository skills and `package.json`; edit those, not this folder.',
      '',
      `It runs ThumbGate ${version} from npm, pinned to that exact version, for the MCP server and the hooks:`,
      '',
      '- **PreToolUse:** checks each tool call against your prevention rules and the default gates before it runs.',
      '- **UserPromptSubmit:** captures thumbs-up and thumbs-down feedback from your prompts.',
      '- **Skills:** capture feedback, turn a mistake into a rule, list rules, see what was blocked, check the wiring.',
      '',
      'ThumbGate is warn-by-default. Set `THUMBGATE_STRICT_ENFORCEMENT=1` to block instead of warn.',
      '',
      'Data: feedback and rules stay on your machine. The CLI sends usage telemetry to thumbgate.ai unless',
      '`DO_NOT_TRACK=1` or `THUMBGATE_NO_TELEMETRY=1` is set. Privacy policy: https://thumbgate.ai/privacy',
      '',
      'Docs: https://thumbgate.ai/guide',
      '',
    ].join('\n'),
    LICENSE: fs.readFileSync(path.join(ROOT, 'LICENSE'), 'utf8'),
    '.claude-plugin/icon.png': fs.readFileSync(path.join(ROOT, 'public', 'assets', 'brand', 'thumbgate-icon-512.png')),
  };
  for (const name of SKILLS) Object.assign(files, skillFiles(name));
  return files;
}

function listFiles(dir, base = dir) {
  if (!fs.existsSync(dir)) return [];
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...listFiles(full, base));
    else out.push(path.relative(base, full).split(path.sep).join('/'));
  }
  return out.sort();
}

function diff() {
  const expected = expectedFiles();
  const problems = [];
  for (const [rel, content] of Object.entries(expected)) {
    const full = path.join(OUT, rel);
    if (!fs.existsSync(full)) problems.push(`missing ${rel}`);
    else if (!fs.readFileSync(full).equals(Buffer.isBuffer(content) ? content : Buffer.from(content))) problems.push(`stale ${rel}`);
  }
  for (const rel of listFiles(OUT)) {
    if (!(rel in expected)) problems.push(`unexpected ${rel}`);
  }
  return { expected, problems };
}

function write() {
  const { expected } = diff();
  fs.rmSync(OUT, { recursive: true, force: true });
  for (const [rel, content] of Object.entries(expected)) {
    const full = path.join(OUT, rel);
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, content);
  }
  return Object.keys(expected).length;
}

module.exports = { expectedFiles, diff, OUT, SKILLS };

if (require.main === module) {
  if (process.argv.includes('--check')) {
    const { problems } = diff();
    if (problems.length) {
      console.error(`plugins/claude-directory is out of date (run node scripts/build-claude-directory-plugin.js):\n  ${problems.join('\n  ')}`);
      process.exit(1);
    }
    console.log('plugins/claude-directory is up to date');
  } else {
    console.log(`wrote ${write()} files to plugins/claude-directory`);
  }
}
